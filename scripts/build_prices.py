"""Build prices.json (what the website shows) from the history files in data/.

For every item: "now" = the newest value in its file, then the value 1, 3 and 5 years before that date
(the last row on or before that day / month). The site shows only those four numbers; the full history stays
in the CSV files. Runs on GitHub every day and whenever a file in data/ is changed.

  data/fuel-daily.csv     date,petrol_per_litre,diesel_per_litre      (automatic, from PPAC)
  data/fuel-monthly.csv   month,lpg_cylinder,cng_per_kg,autolpg_per_litre   (you, once a month)
  data/metals-daily.csv   date,gold22_per_gram,gold24_per_gram,silver_per_kg (you, daily)
"""
import csv, json, datetime as dt
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "prices.json"
PPAC = "PPAC, Govt of India (daily)"
ITEMS = [  # group, id, name, unit, file, column, source
    ("fuel", "petrol", "Petrol", "per litre", "fuel-daily.csv", "petrol_per_litre", PPAC),
    ("fuel", "diesel", "Diesel", "per litre", "fuel-daily.csv", "diesel_per_litre", PPAC),
    ("fuel", "lpg", "LPG cylinder", "14.2 kg, domestic", "fuel-monthly.csv", "lpg_cylinder", "Inflation Tracker price data"),
    ("fuel", "cng", "CNG", "per kg", "fuel-monthly.csv", "cng_per_kg", "Inflation Tracker price data"),
    ("fuel", "autolpg", "Auto-LPG", "per litre", "fuel-monthly.csv", "autolpg_per_litre", "Inflation Tracker price data"),
    ("metals", "gold22", "Gold 22K", "per gram", "metals-daily.csv", "gold22_per_gram", "Chennai retail rate"),
    ("metals", "gold24", "Gold 24K", "per gram", "metals-daily.csv", "gold24_per_gram", "Chennai retail rate"),
    ("metals", "silver", "Silver", "per kg", "metals-daily.csv", "silver_per_kg", "Chennai retail rate"),
]
# a "now" older than this is not shown (so a forgotten item doesn't sit on the site looking current)
STALE_DAYS = {"daily": 45, "monthly": 100}

def to_date(key):
    """'2026-11-20' -> date; '2026-10' -> last day of that month."""
    parts = [int(x) for x in key.split("-")]
    if len(parts) == 3:
        return dt.date(*parts)
    y, m = parts
    nxt = dt.date(y + (m == 12), m % 12 + 1, 1)
    return nxt - dt.timedelta(days=1)

def city(where):
    w = (where or "").lower()
    return "trichy" if ("trichy" in w or "tiruchirappalli" in w or "tiruchi" in w) else "chennai"

def years_before(d, n):
    try:
        return d.replace(year=d.year - n)
    except ValueError:
        return d.replace(year=d.year - n, day=28)

def load(file, column):
    path = ROOT / "data" / file
    out = []
    if not path.exists():
        return out, "daily"
    with path.open(encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        keycol = reader.fieldnames[0]
        for r in reader:
            key, raw = (r.get(keycol) or "").strip(), (r.get(column) or "").strip().replace(",", "")
            if not key or not raw:
                continue
            try:
                # optional "<column>_where" says where the price came from (e.g. "KR Fuels, Trichy")
                where = (r.get(column.rsplit("_per_", 1)[0] + "_where") or "").strip()
                out.append((to_date(key), key, float(raw), where))
            except ValueError:
                print(f"  skipped a row in {file}: {key!r} / {raw!r} is not a date and a number")
    out.sort()
    return out, ("monthly" if keycol == "month" else "daily")

def main():
    today = dt.date.today()
    data = {"city": "Chennai", "built": today.isoformat(),
            "note": "Made automatically from the files in data/. Do not edit this file; edit the CSV files instead.",
            "fuel": [], "metals": []}
    for group, iid, name, unit, file, column, source in ITEMS:
        rows, kind = load(file, column)
        item = {"id": iid, "name": name, "unit": unit, "source": source, "asOf": None, "now": None, "oneYear": None, "threeYears": None, "fiveYears": None}
        if rows:
            d_now, key_now, v_now, where_now = rows[-1]
            if (today - d_now).days <= STALE_DAYS[kind]:
                item.update(asOf=key_now, now=v_now)
                if where_now:
                    item["where"] = where_now
                    item["source"] = f"{where_now} (pump price)"
                for field, n in (("oneYear", 1), ("threeYears", 3), ("fiveYears", 5)):
                    target = years_before(d_now, n)
                    # compare like with like: only history from the same city (a Trichy price is never set against
                    # Chennai). A row with no place written counts as Chennai (the workbook's city).
                    hits = [r for r in rows if r[0] <= target and city(r[3]) == city(where_now)]
                    # only use a value close to the target date (within 40 days for daily, 2 months for monthly)
                    if hits and (target - hits[-1][0]).days <= (40 if kind == "daily" else 62):
                        item[field] = hits[-1][2]
            else:
                print(f"  {name}: latest value is from {key_now}, too old to show (add a newer row)")
        data[group].append(item)
        print(f"{name:13} now {item['now']} ({item['asOf']}) | 1y {item['oneYear']} | 3y {item['threeYears']} | 5y {item['fiveYears']}")
    OUT.write_text(json.dumps(data, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")

if __name__ == "__main__":
    main()
